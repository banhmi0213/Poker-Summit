// Builds the one-time production upgrade for the ring release (owner 2026/10/27).
// Production already has the tournament settings, ring table admin (production_ring_admin_and_removal) and news.
// This concatenates the game migrations production lacks (scripts/poker-release/production-migrations.txt, in order)
// and makes the statements that touch objects production already has idempotent, so it can be re-run safely.
// Usage: node scripts/poker-release/build-production-sql.cjs > scripts/poker-release/production-upgrade.sql
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../..'),list=fs.readFileSync(path.join(__dirname,'production-migrations.txt'),'utf8').split('\n').map(s=>s.trim()).filter(Boolean);
const wrap=stmt=>`do $release$ begin ${stmt}; exception when duplicate_object or duplicate_table then null; end $release$;`;
function idempotent(sql){
 return sql
  .replace(/create table (?!if not exists)/gi,'create table if not exists ')
  .replace(/create (unique )?index (?!if not exists)/gi,(m,u)=>`create ${u??''}index if not exists `)
  .replace(/add column (?!if not exists)/gi,'add column if not exists ')
  .replace(/create schema (?!if not exists)/gi,'create schema if not exists ')
  // Policies and triggers have no IF NOT EXISTS: skip them when they already exist (never dropped).
  .replace(/(^|;)(\s*)(create (?:policy|trigger) [^;]+)(?=;)/gi,(m,lead,ws,stmt)=>`${lead}${ws}${wrap(stmt)}`.replace(/;;$/,';'));
}
const out=['-- Generated by scripts/poker-release/build-production-sql.cjs. Production ring release: one transaction.','begin;'];
for(const name of list){const file=fs.readdirSync(path.join(root,'supabase/migrations')).find(f=>f.endsWith('_'+name+'.sql')||f===name+'.sql');if(!file)throw Error('missing migration '+name);
 out.push(`-- ${file}`,idempotent(fs.readFileSync(path.join(root,'supabase/migrations',file),'utf8').replace(/^\s*(begin|commit)\s*;\s*$/gim,'-- (own transaction removed: the whole upgrade is one transaction)')).replace(/;\s*do \$release\$/g,'; do $release$'));}
out.push('commit;');process.stdout.write(out.join('\n')+'\n');
